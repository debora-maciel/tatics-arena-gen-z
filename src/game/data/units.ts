import type {
  Ability,
  AbilityKind,
  Cost,
  Origin,
  Role,
  UnitDef,
} from "../types";

type Base = {
  hp: number;
  ad: number;
  atkSpeed: number;
  range: number;
  armor: number;
  mana: number;
};

const ability = (kind: AbilityKind, name: string, ratio: number): Ability => ({
  kind,
  name,
  ratio,
});

